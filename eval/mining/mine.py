DEFAULT_OUT = REPO / "eval" / "mining" / "out"

# dataset topic -> the palace whose lore the topic describes (12 cung)
TOPIC_PALACE = {
    "overview": "soulPalace",
    "personality": "soulPalace",
    "love": "spousePalace",
    "career": "careerPalace",
    "wealth": "wealthPalace",
    "health": "healthPalace",
    "family": "siblingsPalace",
    "children": "childrenPalace",
    "move": "surfacePalace",
    "friends": "friendsPalace",
    "home": "propertyPalace",
    "spirit": "spiritPalace",
    "parents": "parentsPalace",
}

BRANCH_INDEX = [
    "ziEarthly", "chouEarthly", "yinEarthly", "maoEarthly", "chenEarthly",
    "siEarthly", "wuEarthly", "weiEarthly", "shenEarthly", "youEarthly",
    "xuEarthly", "haiEarthly",
]
STEM_INDEX = [
    "jiaHeavenly", "yiHeavenly", "bingHeavenly", "dingHeavenly",
    "wuHeavenly", "jiHeavenly", "gengHeavenly", "xinHeavenly",
    "renHeavenly", "guiHeavenly",
]
SIHUA_KIND = {"禄": "lu", "权": "quan", "科": "ke", "忌": "ji"}
PALACE_NAME_ALIASES = {"交友": "friendsPalace", "仆役": "friendsPalace"}
PALACE_KEYS = (
    "soulPalace", "siblingsPalace", "spousePalace", "childrenPalace",
    "wealthPalace", "healthPalace", "surfacePalace", "friendsPalace",
    "careerPalace", "propertyPalace", "spiritPalace", "parentsPalace",
)

_SENT_SPLIT = re.compile(r"[。！？!?\n；;]+")
_MARKDOWN = re.compile(r"\*\*|【|】|⭐|「|」|《|》|#+")
_EMOJI = re.compile(
    "[\U0001F000-\U0001FAFF\u2600-\u27BF\u2B00-\u2BFF\uFE0F]"
)
_BAD_PREFIX = re.compile(r"^[-—\s:·•◆◇▶]+")
_WS = re.compile(r"\s+")
TOPIC_LIST = sorted(TOPIC_PALACE)  # bitmask order for topics_of


def _build_maps() -> tuple[dict[str, str], dict[str, str], dict[str, str]]:
    """zh name -> entity key maps from the engine's builtin zh-CN pack."""
    from x_iztro.knowledge import KnowledgePack  # eval-only import (I22 tooling)

    pack = KnowledgePack.builtin("zh-CN")
    star_zh2key = {s.name: s.key for s in pack.stars() if s.name}
    pattern_zh2key = {}
    for p_ in pack.patterns():
        if p_.name:
            pattern_zh2key[p_.name] = p_.key
            pattern_zh2key[p_.name + "格"] = p_.key
    palace_zh2key = dict(PALACE_NAME_ALIASES)
    for key in PALACE_KEYS:
        e = pack.palace(key)
        if e and e.name:
            palace_zh2key[e.name] = key
    return star_zh2key, pattern_zh2key, palace_zh2key


def _clean(sentence: str) -> str:
    s = _MARKDOWN.sub("", sentence)
    s = _EMOJI.sub("", s)
    s = _BAD_PREFIX.sub("", s)
    return _WS.sub(" ", s).strip()


def _natal_mutagens(chart: dict) -> dict[str, str]:
    """starKey -> lu/quan/ke/ji, from the palace whose stem is the year stem."""
    try:
        stem_key = chart["rawDates"]["chineseDate"]["yearlyKeys"][0]
    except (KeyError, IndexError, TypeError):
        return {}
    kinds = ["lu", "quan", "ke", "ji"]
    for p in chart["palaces"]:
        if p["heavenlyStemKey"] == stem_key:
            keys = p.get("mutagenStarKeys") or []
            if len(keys) == 4:
                return {k: kinds[i] for i, k in enumerate(keys)}
    return {}


def _signature_and_drift(sample_chart: dict, dto_chart: dict) -> tuple[bool, dict]:
    """Compare dataset structural facts vs our recast; return (keep, sig).

    Drift (drop the sample): soul palace branch, ziwei branch, per-branch
    major-star key sets, palace names, or natal mutagen assignment differ.
    """
    palaces = dto_chart["palaces"]
    branch_palace = {
        BRANCH_INDEX.index(p["earthlyBranchKey"]): p for p in palaces
    }
    soul_idx = next(
        (
            BRANCH_INDEX.index(p["earthlyBranchKey"])
            for p in palaces
            if p["nameKey"] == "soulPalace"
        ),
        -1,
    )
    our_mutagens = _natal_mutagens(dto_chart)

    their = sample_chart
    if int(their.get("mingGongBranch", -1)) != soul_idx:
        return False, {}
    ziwei_branch = int(their.get("ziweiPos", -1))
    our_ziwei_branch = next(
        (
            BRANCH_INDEX.index(p["earthlyBranchKey"])
            for p in palaces
            if any(s["key"] == "ziweiMaj" for s in p.get("majorStars") or [])
        ),
        -1,
    )
    if ziwei_branch != our_ziwei_branch:
        return False, {}

    sig: dict[str, Any] = {
        "stars": set(),
        "stars_by_branch": collections.defaultdict(set),
        "mutagens": our_mutagens,
        "patterns": {p["key"] for p in dto_chart.get("patterns") or []},
        "palaces_by_branch": {},
        "vn_names": {},
    }
    their_mutagens: dict[str, str] = {}
    for dp in their["palaces"]:
        b = int(dp["branch"])
        op = branch_palace.get(b)
        if op is None:
            return False, {}
        name_key = _PALACE_ZH2KEY.get(dp["name"])
        if name_key != op["nameKey"]:
            return False, {}
        sig["palaces_by_branch"][b] = name_key
        their_majors = {}
        for s in dp["stars"]:
            key = _STAR_ZH2KEY.get(s["name"])
            if s.get("type") == "major" and key:
                their_majors[key] = s
            if key:
                sig["stars"].add(key)
            sihua = s.get("siHua") or ""
            if sihua:
                # mutagens land on non-major stars too (e.g. 文曲化忌) —
                # an unmapped kind or star means we cannot compare → drop
                kind = SIHUA_KIND.get(sihua)
                if key is None or kind is None:
                    return False, {}
                their_mutagens[key] = kind
        if set(their_majors) != {s["key"] for s in op.get("majorStars") or []}:
            return False, {}
        sig["stars_by_branch"][b] = set(their_majors)
        sig["palace_by_name"] = {v: b for b, v in sig["palaces_by_branch"].items()}
        for s in op.get("majorStars") or []:
            sig["vn_names"][s["key"]] = s["name"]
        for s in op.get("minorStars") or []:
            sig["vn_names"][s["key"]] = s["name"]
    # natal mutagen assignment must match exactly, both directions
    if our_mutagens != their_mutagens:
        return False, {}
    return True, sig


def _names_in(text: str) -> set[str]:
    return {m.group(0) for m in _NAME_RE.finditer(text)}


def process_file(
    path: Path,
) -> tuple[collections.Counter, dict, dict[str, str], collections.Counter]:
    """One gzipped JSONL file -> local counters (runs inside Pool workers)."""
    assert _ENGINE is not None and _PROFILE is not None
    counts: collections.Counter = collections.Counter()  # (entity, phrase) -> n
    topics_of: dict = collections.defaultdict(int)  # (entity, phrase) -> bitmask
    vn_names: dict[str, str] = {}
    stats: collections.Counter = collections.Counter()

    with gzip.open(path, "rt", encoding="utf-8") as fh:
        for lineno, line in enumerate(fh, 1):
            if _LIMIT_LINES and lineno > _LIMIT_LINES:
                break
            stats["lines"] += 1
            try:
                sample = json.loads(line)
            except json.JSONDecodeError:
                stats["bad_json"] += 1
                continue
            bi = sample.get("birthInfo") or {}
            try:
                birth = SimpleNamespace(
                    correctedSolarDate=dt.date(
                        int(bi["year"]), int(bi["month"]), int(bi["day"])
                    ),
                    timeIndex=int(bi["hour"]),
                    gender=str(bi["gender"]),
                )
                dto = _ENGINE.cast_chart(
                    cast("NormalizedBirthMoment", birth), _PROFILE
                )
            except Exception:  # date/timeIndex out of range etc.
                stats["cast_error"] += 1
                continue
            keep, sig = _signature_and_drift(sample["chart"], dto.chart)
            if not keep:
                stats["drifted"] += 1
                continue
            stats["kept"] += 1
            vn_names.update(sig["vn_names"])
            seen: set = set()  # count each (entity, phrase) once per SAMPLE

            def _hit(
                ek: str, phrase: str, bit: int, _seen: set = seen
            ) -> None:
                pair = (ek, phrase)
                if pair in _seen:
                    return
                _seen.add(pair)
                counts[pair] += 1
                topics_of[pair] |= bit

            for topic, text in (sample.get("topics") or {}).items():
                if not isinstance(text, str):
                    continue
                palace_key = TOPIC_PALACE.get(topic, "")
                topic_bit = (
                    1 << TOPIC_LIST.index(topic) if topic in TOPIC_LIST else 0
                )
                for raw in _SENT_SPLIT.split(text):
                    phrase = _clean(raw)
                    if not (10 <= len(phrase) <= 200):
                        continue
                    names = _names_in(phrase)
                    star_keys = {
                        _STAR_ZH2KEY[n] for n in names if n in _STAR_ZH2KEY
                    } & sig["stars"]
                    pat_keys = {
                        _PAT_ZH2KEY[n] for n in names if n in _PAT_ZH2KEY
                    } & sig["patterns"]
                    pal_keys = {
                        _PALACE_ZH2KEY[n] for n in names if n in _PALACE_ZH2KEY
                    }
                    if star_keys or pat_keys:
                        for k in star_keys:
                            _hit(f"star:{k}", phrase, topic_bit)
                            for b, stars in sig["stars_by_branch"].items():
                                if k in stars:
                                    pk = sig["palaces_by_branch"][b]
                                    _hit(
                                        f"palaceStar:{pk}:{k}",
                                        phrase,
                                        topic_bit,
                                    )
                            kind = sig["mutagens"].get(k)
                            if kind:
                                _hit(
                                    f"mutagenStar:{kind}:{k}",
                                    phrase,
                                    topic_bit,
                                )
                        for k in pat_keys:
                            _hit(f"pattern:{k}", phrase, topic_bit)
                    else:
                        # no star/pattern named — palace-conditional lore:
                        # attribute to the topic's palace only; the
                        # co-located stars go to parked palaceStar keys,
                        # never to bare `star:`/`mutagenStar:` (that would
                        # leak chart-specific claims into generic intros)
                        if palace_key:
                            _hit(f"palace:{palace_key}", phrase, topic_bit)
                            b = sig["palace_by_name"].get(palace_key)
                            if b is not None:
                                for k in sig["stars_by_branch"].get(b, ()):
                                    _hit(
                                        f"palaceStar:{palace_key}:{k}",
                                        phrase,
                                        topic_bit,
                                    )
                                    kind = sig["mutagens"].get(k)
                                    if kind:
                                        _hit(
                                            f"mutagenStar:{kind}:{k}",
                                            phrase,
                                            topic_bit,
                                        )
                        for pk in pal_keys - {palace_key}:
                            _hit(f"palace:{pk}", phrase, topic_bit)
    return counts, topics_of, vn_names, stats


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-dir", type=Path, default=DEFAULT_DATA)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument(
        "--workers", type=int, default=max(1, mp.cpu_count() - 1)
    )
    ap.add_argument("--limit-files", type=int, default=0)
    ap.add_argument("--limit-lines", type=int, default=0)
    ap.add_argument("--min-count", type=int, default=3)
    args = ap.parse_args()

    files = sorted(args.data_dir.glob("year-*/*.jsonl.gz"))
    if args.limit_files:
        files = files[: args.limit_files]
    if not files:
        print(f"no files under {args.data_dir}", file=sys.stderr)
        return 1
    args.out.mkdir(parents=True, exist_ok=True)

    merged: collections.Counter = collections.Counter()
    merged_topics: dict = collections.defaultdict(int)
    vn_names: dict[str, str] = {}
    stats: collections.Counter = collections.Counter()
    t0 = time.time()
    with mp.Pool(
        args.workers,
        initializer=_init_worker,
        initargs=(args.limit_lines,),
    ) as pool:
        for i, (counts, topics_of, names, st) in enumerate(
            pool.imap_unordered(process_file, files), 1
        ):
            merged.update(counts)
            for k, v in topics_of.items():
                merged_topics[k] |= v
            vn_names.update(names)
            stats.update(st)
            del counts, topics_of
            if i % 20 == 0 or i == len(files):
                print(
                    f"{i}/{len(files)} files — kept={stats['kept']} "
                    f"drifted={stats['drifted']} "
                    f"elapsed={time.time() - t0:.0f}s",
                    flush=True,
                )

    total = stats["kept"] + stats["drifted"]
    drift_rate = stats["drifted"] / total if total else 0.0

    by_entity: dict[str, list] = collections.defaultdict(list)
    for (entity, phrase), n in merged.items():
        if n < args.min_count:
            continue
        by_entity[entity].append(
            {
                "text": phrase,
                "count": n,
                "topics": [
                    t
                    for i, t in enumerate(TOPIC_LIST)
                    if merged_topics.get((entity, phrase), 0) & (1 << i)
                ],
            }
        )

    out_file = args.out / "candidates.jsonl"
    n_phrases = 0
    with out_file.open("w", encoding="utf-8") as fh:
        for entity in sorted(by_entity):
            rows = sorted(by_entity[entity], key=lambda r: -r["count"])
            etype, _, key = entity.partition(":")
            fh.write(
                json.dumps(
                    {
                        "entity": entity,
                        "entityType": etype,
                        "key": key,
                        "name": vn_names.get(key, ""),
                        "phrases": rows,
                    },
                    ensure_ascii=False,
                )
                + "\n"
            )
            n_phrases += len(rows)

    stats_out = {
        "files": len(files),
        "lines": stats["lines"],
        "kept": stats["kept"],
        "drifted": stats["drifted"],
        "driftRate": round(drift_rate, 4),
        "badJson": stats["bad_json"],
        "castErrors": stats["cast_error"],
        "entities": len(by_entity),
        "phrases": n_phrases,
        "minCount": args.min_count,
    }
    (args.out / "stats.json").write_text(
        json.dumps(stats_out, ensure_ascii=False, indent=2)
    )
    print(json.dumps(stats_out, ensure_ascii=False))
    return 0


# --- per-worker globals (set by _init_worker) --------------------------------

_ENGINE: XiztroEngine | None = None
_PROFILE: EngineProfile | None = None
_LIMIT_LINES = 0
_STAR_ZH2KEY: dict = {}
_PAT_ZH2KEY: dict = {}
_PALACE_ZH2KEY: dict = {}
_NAME_RE: re.Pattern = re.compile("$.")  # never matches


def _init_worker(limit_lines: int) -> None:
    global _ENGINE, _PROFILE, _LIMIT_LINES
    global _STAR_ZH2KEY, _PAT_ZH2KEY, _PALACE_ZH2KEY, _NAME_RE
    from app.domain.chart.contracts import EngineProfile
    from app.infrastructure.xiztro.engine import XiztroEngine

    _ENGINE = XiztroEngine()
    _PROFILE = EngineProfile(id="iztro-default-v1", engineVersion="0.6.1")
    _LIMIT_LINES = limit_lines
    _STAR_ZH2KEY, _PAT_ZH2KEY, _PALACE_ZH2KEY = _build_maps()
    names = sorted(
        set(_STAR_ZH2KEY) | set(_PAT_ZH2KEY) | set(_PALACE_ZH2KEY),
        key=len,
        reverse=True,
    )
    _NAME_RE = re.compile("|".join(re.escape(n) for n in names))


if __name__ == "__main__":
    raise SystemExit(main())
