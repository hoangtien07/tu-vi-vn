"""SPEC_V05 D1 — mine Renhuai dataset v3 → candidates.jsonl.

Per sample (eval/dataset/samples/ziwei-samples-toolkit/samples-out/year-*/Y-M.jsonl.gz):

  1. Re-cast the chart with the production engine config (I22 drift filter —
     the dataset was generated by an older engine; samples whose structure
     diverges are dropped).
  2. Split each of the 13 topic texts into sentences and attribute each
     sentence to entity keys using zh names it mentions — star:{key},
     palace:{nameKey} (sentences with no star/pattern mention),
     pattern:{key} (validated against OUR recast pattern hits).
     Palace-conditional and mutagen-conditional phrases also emit parked
     composite keys (palaceStar:…, mutagenStar:…) for a future schema
     extension; pack.py ignores them today.
  3. Keep phrases recurring across >= --min-count distinct samples.

Output: eval/mining/out/candidates.jsonl + stats.json (drift rate,
coverage). Dataset never leaves eval/dataset/ (gitignored).

Run (needs the api venv — x-iztro + app package):

    cd apps/api && uv run python ../../eval/mining/mine.py \
        --workers 8 [--limit-files 3] [--min-count 3]
"""

